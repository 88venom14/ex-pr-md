SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS `product`;
CREATE TABLE `product` (
  `article` varchar(20) NOT NULL,
  `product_name` varchar(255) NOT NULL,
  `unit_name` varchar(50) DEFAULT NULL,
  `price` decimal(10,2) NOT NULL DEFAULT '0.00',
  `supplier_name` varchar(100) DEFAULT NULL,
  `manufacturer_name` varchar(100) DEFAULT NULL,
  `category_name` varchar(100) DEFAULT NULL,
  `discount_percent` int NOT NULL DEFAULT '0',
  `stock_quantity` int NOT NULL DEFAULT '0',
  `description` text,
  `photo_file` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`article`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

DROP TABLE IF EXISTS `user_account`;
CREATE TABLE `user_account` (
  `user_id` int NOT NULL AUTO_INCREMENT,
  `role_name` varchar(50) NOT NULL,
  `full_name` varchar(100) NOT NULL,
  `login` varchar(50) NOT NULL,
  `password` varchar(50) NOT NULL,
  PRIMARY KEY (`user_id`),
  UNIQUE KEY `uq_user_full_name` (`full_name`)
) ENGINE=InnoDB AUTO_INCREMENT=11 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

DROP TABLE IF EXISTS `pickup_point`;
CREATE TABLE `pickup_point` (
  `pickup_point_id` int NOT NULL,
  `address` varchar(200) NOT NULL,
  PRIMARY KEY (`pickup_point_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

DROP TABLE IF EXISTS `customer_order`;
CREATE TABLE `customer_order` (
  `order_id` int NOT NULL,
  `items` varchar(500) NOT NULL,
  `order_date` date DEFAULT NULL,
  `delivery_date` date DEFAULT NULL,
  `pickup_point_id` int DEFAULT NULL,
  `client` varchar(100) NOT NULL,
  `receive_code` varchar(10) DEFAULT NULL,
  `status` varchar(50) DEFAULT NULL,
  PRIMARY KEY (`order_id`),
  KEY `fk_order_point` (`pickup_point_id`),
  KEY `fk_order_client` (`client`),
  CONSTRAINT `fk_order_client` FOREIGN KEY (`client`) REFERENCES `user_account` (`full_name`),
  CONSTRAINT `fk_order_point` FOREIGN KEY (`pickup_point_id`) REFERENCES `pickup_point` (`pickup_point_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

